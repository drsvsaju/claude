import { b, device, signup, wait, log, check, errs, failCount, until } from './cl-common.mjs';
const A = await device('A');
await signup(A, 'cl_al' + Date.now().toString(36).slice(-4));
await A.ev(() => showTab('clan')); await wait(400);
check('no-clan screen', await A.ev(() => !!$('#clanCreateBtn')));
await A.p.click('#clanCreateBtn'); await A.p.fill('#ccName', 'Smoke Owls ' + Date.now().toString(36).slice(-3)); await A.p.fill('#ccTag', 'smk'); await A.p.click('#ccSave');
const t = await until(A, () => inClan());
check('created', t >= 0, JSON.stringify(await A.ev(() => ({ err: $('#ccErr').textContent }))));
await wait(800);
log(await A.ev(() => JSON.stringify({ doc: CLAN.doc && CLAN.doc.name, role: myClanRole(), members: (CLAN.members || []).length, code: CLAN.info && CLAN.info.code })));
await A.p.screenshot({ path: 'sm-clan.png', fullPage: true });
log('errors', JSON.stringify(errs.slice(0, 10)));
await b.close();
process.exit(failCount() ? 1 : 0);
