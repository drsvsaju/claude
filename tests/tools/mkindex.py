"""Build notes/v2.0-codemap/07-js-function-index.md: every section of the script in index.html with its functions.
Deterministic (no reading needed): section headers are the '/* ====' blocks; functions are top-level declarations."""
import re, sys
src = '/home/user/claude/index.html'
lines = open(src, encoding='utf-8').read().split('\n')
start = next(i for i, l in enumerate(lines) if i > 4000 and l.strip() == '<script>')
end = len(lines)
sections = []  # (line, title)
i = start
while i < end - 1:
    if re.match(r'^/\* ={20,}', lines[i]):
        title = lines[i + 1].strip()
        sections.append((i + 2, title))
        i += 2
    else:
        i += 1
fn_re = re.compile(r'^(?:async\s+)?function\s*\*?\s*([A-Za-z_$][\w$]*)\s*\(([^)]*)')
const_fn_re = re.compile(r'^(?:const|let)\s+([A-Za-z_$][\w$]*)\s*=\s*(?:async\s*)?(?:\(([^)]*)\)|([A-Za-z_$][\w$]*))\s*=>')
const_re = re.compile(r'^(?:const|let)\s+([A-Z][A-Z0-9_]{2,})\s*=')
out = ['# JS function index — index.html script (v1.20, commit 77f8456)', '',
       'Generated by a script from the section headers and top-level declarations. Line numbers are for v1.20 and drift as',
       'the file is edited: search by NAME. `f` = function, `c` = UPPER_CASE constant/table. Doc comments directly above a',
       'function are shown when they are one line.', '']
bounds = sections + [(end, 'END')]
total = 0
for k, (ln, title) in enumerate(sections):
    nxt = bounds[k + 1][0]
    items = []
    for j in range(ln, min(nxt - 2, end)):
        l = lines[j]
        m = fn_re.match(l) or const_fn_re.match(l)
        if m:
            name = m.group(1); args = (m.group(2) or (m.group(3) if m.lastindex and m.lastindex >= 3 else '') or '').strip()
            doc = ''
            p = lines[j - 1].strip() if j > 0 else ''
            if p.startswith('/**') and p.endswith('*/'):
                doc = p[3:-2].strip()
            elif p.startswith('//'):
                doc = p[2:].strip()
            if len(doc) > 150: doc = doc[:147] + '…'
            items.append(f'- f `{name}({args[:60]})` · {j + 1}' + (f' — {doc}' if doc else ''))
            total += 1
            continue
        m = const_re.match(l)
        if m:
            items.append(f'- c `{m.group(1)}` · {j + 1}')
    out.append(f'## {title[:110]} — lines {ln}–{nxt - 2}')
    out.extend(items if items else ['- (no top-level declarations)'])
    out.append('')
open('/home/user/claude/notes/v2.0-codemap/07-js-function-index.md', 'w', encoding='utf-8').write('\n'.join(out))
print('sections', len(sections), 'functions', total, 'lines', len(out))
