// node shot.mjs <width> <view-js> <out.png> [scrollY|full] — screenshot with the audit's populated data
import { chromium } from 'playwright';
import fs from 'fs';
const [w, js, out, scroll] = process.argv.slice(2);
const FBDIR = new URL('./node_modules/firebase/', import.meta.url).pathname;
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const src = fs.readFileSync(new URL('./audit.mjs', import.meta.url), 'utf8'); const seedSrc = src.slice(src.indexOf('const seed = '), src.indexOf('const check = '));
const LONG = 'Organic Chemistry – Aldehydes, Ketones and Carboxylic Acids (revision part 2)';
const seed = eval(seedSrc.replace('const seed = ', '(').replace(/;\s*$/, ')'));
const touch = +w < 900;
const ctx = await b.newContext({ viewport: { width: +w, height: touch ? 844 : 900 }, hasTouch: touch, isMobile: +w < 700, colorScheme: process.env.SCHEME || 'light' });
await ctx.route('https://www.gstatic.com/firebasejs/**', r => r.fulfill({ body: fs.readFileSync(FBDIR + r.request().url().split('/').pop()), contentType: 'application/javascript' }));
await ctx.route('https://fonts.googleapis.com/**', r => r.fulfill({ body: '', contentType: 'text/css' }));
const p = await ctx.newPage(); p.on('pageerror', e => console.log('ERR', e.message));
await p.goto('http://localhost:8000/index.html'); await p.evaluate(seed, LONG);
if (process.env.GLASS) await p.evaluate(g => localStorage.setItem('pomodorolist-glass', g), process.env.GLASS);
await p.goto('http://localhost:8000/index.html'); await p.waitForSelector('#appView:not(.hidden)'); await new Promise(r => setTimeout(r, 1800));
await p.evaluate(() => { document.querySelectorAll('dialog[open]').forEach(x => x.close()); $$('.pomeo-bubble').forEach(x => x.classList.add('hidden')); $$('.toast-item').forEach(x => x.remove()); });
await p.evaluate(js); await new Promise(r => setTimeout(r, 1200));
if (scroll && scroll !== 'full') await p.evaluate(y => window.scrollTo(0, +y), scroll);
await p.evaluate(() => $$('.toast-item').forEach(x => x.remove()));
await p.screenshot({ path: out, fullPage: scroll === 'full' });
await b.close();
